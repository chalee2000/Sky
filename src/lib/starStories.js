import { stars, constellations } from './astronomy.js';
import { getStarScience } from './starScience.js';

// The setting is fictional. Numbers and classifications come from the named
// source catalog, with no invented physical properties or naming dates.
export function createStarStory(star, constellation) {
  const science=getStarScience(star);
  const distance=science.distanceText;
  const group=constellation.name;
  const paragraphs = star.id === 'alnasl' ? [
    `ค่ำหนึ่ง เด็กน้อยนั่งข้างยายแล้วเปิดแผนที่กลุ่มดาว${group} “อัลนาสล์อยู่ตรงไหนจ๊ะ” ยายชวนมองชื่อ Alnasl แล้วอ่านชื่อทางดาราศาสตร์ ${science.designation} ให้ฟัง “ชื่อหลายแบบช่วยให้เราตามหาดาวดวงเดียวกันในหนังสือคนละเล่มได้”`,
    `“ปลายลูกศร” ยายอ่านความหมายของชื่อให้ฟัง “ในบันทึกดาวอัลศูฟี ดาวดวงนี้อยู่ที่ปลายลูกศรของภาพคนยิงธนูบนท้องฟ้า” เด็กน้อยใช้นิ้วตามเส้นบนแผนที่ ยายยิ้มแล้วบอกว่า “เป็นภาพที่คนใช้เล่าและจดจำตำแหน่งนะ ตัวดาวไม่ได้เป็นลูกศรจริง ๆ”`,
    `ยายเปิดข้อมูลอีกหน้า “แค็ตตาล็อก Bright Star Catalogue ระบุสเปกตรัม ${science.spectralType} ซึ่งจัดเป็น${science.starType} ตัว K บอกกลุ่มสเปกตรัม และ III คือชั้นความส่องสว่างของดาวยักษ์ เรารู้จักดาวผ่านแสงที่ตรวจวัดได้ ไม่ใช่เดาชนิดจากขนาดจุดบนแผนที่”`,
    `“แล้วมันสว่างแค่ไหนจ๊ะ” เด็กน้อยถาม ยายชี้ค่า ${science.magnitudeText} แมกนิจูดใน HYG v4.1 “นี่คือความสว่างปรากฏในแถบ V ที่มองจากโลก ตัวเลขยิ่งน้อยยิ่งสว่าง แต่ยังไม่ใช่พลังงานทั้งหมดที่ดาวปล่อยออกมา” แค็ตตาล็อกเดียวกันให้ระยะทางประมาณ ${distance} ปีแสง หรือราว 96–97 ปีแสง`,
    `เด็กน้อยเงยหน้าจากแผนที่ “แสงเดินทางมานานกว่าที่หนูเกิดอีกนะ” ยายตอบว่า “ใช่จ้ะ ปีแสงเป็นหน่วยระยะทาง แสงจากระยะนี้ใช้เวลาเดินทางประมาณ ${distance} ปี ตัวเลขเป็นค่าประมาณและปรับได้เมื่อมีการวัดใหม่” ทั้งคู่จดชื่ออัลนาสล์ไว้ คืนไหนจะมองเห็นต้องดูเวลา สถานที่ เมฆ และแสงไฟด้วย แต่ทุกครั้งที่กลับมาอ่านชื่อเล็ก ๆ นี้ เด็กน้อยก็จำได้ว่ามันพาเราไปรู้จักแสงจริงจากดาวดวงหนึ่ง`,
  ] : [
    `ค่ำหนึ่งที่ลานบ้าน เด็กน้อยเปิดแผนที่ฟ้าแล้วถามยายว่า “${star.name} คือดาวดวงไหนหรือจ๊ะ” ยายชวนให้ดูชื่อ ${star.nameEn} และชื่อทางดาราศาสตร์ ${science.designation} แล้วบอกว่า “ดาวดวงนี้อยู่ในกลุ่มดาว${group} คืนนี้เราจะเห็นหรือไม่ ต้องดูเวลา สถานที่ และท้องฟ้าด้วย”`,
    `ยายเล่าต่อว่า “${star.description}” แล้วเปิดข้อมูลที่นักดาราศาสตร์จัดหมวดหมู่จากแสงให้ดูว่า Bright Star Catalogue ระบุสเปกตรัม ${science.spectralType} “รหัสนี้เป็นการจัดประเภทในแค็ตตาล็อก ถ้าเป็นระบบดาวหลายดวง เราต้องอ่านด้วยว่าข้อมูลหมายถึงองค์ประกอบไหน”`,
    `“จุดที่สว่างกว่าต้องใหญ่กว่าเสมอไหมจ๊ะ” เด็กน้อยถาม ยายชี้ค่า ${science.magnitudeText} แมกนิจูดของ${star.name}ใน HYG v4.1 “นี่คือความสว่างปรากฏในแถบ V ที่มองจากโลก ตัวเลขยิ่งน้อยยิ่งสว่าง ระยะทางและแสงที่ดาวปล่อยออกมาล้วนมีส่วน จึงใช้ตัวเลขนี้บอกขนาดดาวเพียงอย่างเดียวไม่ได้”`,
    `“แล้วแสงเดินทางมาไกลแค่ไหนจ๊ะ” เด็กน้อยถาม ยายเปิด HYG v4.1 ให้ดู ระยะทางในแค็ตตาล็อกนี้ประมาณ ${distance} ปีแสง “ปีแสงเป็นหน่วยระยะทาง แสงจากระยะเท่านี้ใช้เวลาเดินทางประมาณ ${distance} ปี ตัวเลขเป็นค่าประมาณ โดยเฉพาะดาวไกลอาจมีค่าต่างกันในงานวิจัยใหม่”`,
    `ก่อนเก็บแผนที่ ยายชวนดูรูปกลุ่มดาวอีกครั้ง “${constellation.description}” แล้วฝากว่า “เส้นที่ลากเป็นรูปเป็นวิธีช่วยจำจากมุมมองบนโลก ไม่ใช่เชือกที่ผูกดาวไว้ ดาวในรูปเดียวกันอาจอยู่ห่างจากเราไม่เท่ากัน” เด็กน้อยจึงจดชื่อ${star.name}และแหล่งข้อมูลไว้ เพื่อกลับมาค้นหาต่อด้วยกันในคืนถัดไป`,
  ];
  return {
    starId:star.id,
    constellationId:star.constellationId,
    kind:'scientific-astronomy-storytelling',
    label:'นิทานดวงดาว · อิงวิทยาศาสตร์',
    title:star.id==='alnasl'?'อัลนาสล์ · ปลายลูกศรและแสงที่เดินทางไกล':`ยายเล่าเรื่อง${star.name}ผ่านแสงดาว`,
    paragraphs,
    science,
    source:science.source,
  };
}

export const starStories=Object.fromEntries(stars.map(star=>{
  const constellation=constellations.find(item=>item.id===star.constellationId);
  if(!constellation) throw new Error(`Missing constellation for ${star.id}`);
  return [star.id,createStarStory(star,constellation)];
}));
