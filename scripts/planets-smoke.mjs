import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { planetPositions } from '../src/lib/planets.js';

const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:844},timezoneId:'Asia/Bangkok'});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route('https://alasky.cds.unistra.fr/**',route=>route.abort());
try {
  await page.goto(process.env.SKY_TEST_URL||'http://127.0.0.1:5173/Sky/',{waitUntil:'networkidle'});
  assert.equal(await page.locator('[data-planet-choice]').count(),7);
  await page.locator('[data-planet-choice="saturn"]').click();
  const card=page.locator('[data-selected-planet="saturn"]');
  await card.waitFor();
  assert.match(await card.innerText(),/AU/);
  await card.getByRole('button').click();
  const details=page.locator('[data-planet-details="saturn"]');
  await details.waitFor();
  assert.match(await details.innerText(),/แบบจำลอง 3 มิติ · ไม่ใช่ภาพถ่าย/);
  assert.equal(await details.locator('a[href="https://science.nasa.gov/saturn/"]').getAttribute('href'),'https://science.nasa.gov/saturn/');
  assert.equal(await details.locator('img').count(),0,'moving planets do not reuse a fixed-star survey photo');
  await page.keyboard.press('Escape');
  const before=await card.locator('.star-stats strong').first().innerText();
  await page.locator('.date-control').click();
  await page.getByLabel('วันและเวลา',{exact:true}).fill('2026-10-22T21:00');
  await page.getByRole('button',{name:'แสดงท้องฟ้า',exact:true}).click();
  await page.getByRole('slider').fill('720');
  assert.notEqual(await card.locator('.star-stats strong').first().innerText(),before);
  await page.getByRole('slider').fill('1260');
  assert.ok(await page.locator('.map-planet').count()>0,'above-horizon planets render on the map');
  const marker=page.locator('.map-planet').first();
  const id=await marker.getAttribute('data-planet');
  await marker.focus();
  await page.keyboard.press('Enter');
  await page.locator(`[data-selected-planet="${id}"]`).waitFor();
  const search=page.getByRole('textbox',{name:'ค้นหาดาวหรือกลุ่มดาว'});
  await search.fill('Neptune');
  await page.locator('.search-results button').first().click();
  await page.locator('[data-selected-planet="neptune"]').waitFor();
  await search.fill('ดาวศุกร์');
  await page.keyboard.press('Enter');
  await page.locator('[data-selected-planet="venus"]').waitFor();
  await search.fill('Sirius');
  await page.locator('.search-results button').first().click();
  assert.equal(await page.locator('[data-selected-planet]').count(),0);
  await page.locator('.star-identity h2').filter({hasText:'ซิริอุส'}).waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.addInitScript(()=>{
    const Sensor=class extends Event {};
    Sensor.requestPermission=async()=> 'granted';
    Object.defineProperty(window,'DeviceOrientationEvent',{configurable:true,value:Sensor});
  });
  const sensorTime=new Date('2026-10-22T14:00:00Z');
  await page.clock.install({time:sensorTime});
  await page.reload({waitUntil:'networkidle'});
  const target=planetPositions(sensorTime,13.7563,100.5018).find(p=>p.altitude>5&&p.altitude<85);
  assert.ok(target,'at least one planet is above the Bangkok horizon for the reference test time');
  await page.getByRole('button',{name:'ส่องฟ้าตามมือถือ',exact:true}).click();
  await page.locator('.sky-pointer').waitFor();
  await page.evaluate(target=>{
    const event=new Event('deviceorientation');
    for(const [key,value] of Object.entries({beta:90+target.altitude,gamma:0,absolute:false,webkitCompassHeading:target.azimuth,webkitCompassAccuracy:10})) Object.defineProperty(event,key,{value});
    window.dispatchEvent(event);
  },target);
  const pointer=page.locator(`.pointer-planet[data-planet="${target.id}"]`);
  await pointer.waitFor();
  await pointer.focus();
  await page.keyboard.press('Enter');
  await page.locator(`[data-selected-planet="${target.id}"]`).waitFor();
  assert.equal(await page.locator('.sky-pointer').count(),1,'selecting a planet preserves pointing mode');
  assert.deepEqual(errors,[]);
  console.log('PASS: seven planets, Thai/English search, selection, details and honest image labels, changing time, map keyboard selection, return to stars, mobile layout.');
} finally {await browser.close();}
