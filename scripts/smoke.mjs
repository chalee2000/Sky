import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, timezoneId: 'Asia/Bangkok' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await mkdir('test-results', { recursive: true });
try {
  await page.goto(process.env.SKY_TEST_URL || 'http://127.0.0.1:5173/Sky/?view=map', { waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: 'คืนนี้มีอะไรให้ค้นพบ' }).waitFor();
  assert.ok(await page.locator('.sky-map-svg circle').count() > 1000, 'real catalog is rendered');
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'แสดงเส้นกลุ่มดาว', exact: true }).click();
  assert.equal(await page.locator('.constellation-lines').count(), 0, 'constellation toggle hides lines');
  await page.getByRole('button', { name: 'แสดงเส้นกลุ่มดาว', exact: true }).click();
  await page.getByRole('button', { name: 'ซูมเข้า', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'ซูมออก', exact: true }).isDisabled(), false);
  await page.getByRole('button', { name: 'รีเซ็ตการซูม', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'ซูมออก', exact: true }).isDisabled(), true);
  await page.getByRole('textbox', { name: 'ค้นหาดาวหรือกลุ่มดาว' }).fill('Vega');
  await page.keyboard.press('Tab');
  await page.waitForTimeout(200);
  assert.equal(await page.locator('.search-results button:focus').count(), 1, 'keyboard focus stays in search results');
  await page.keyboard.press('Enter');
  await page.locator('.star-identity h2').filter({ hasText: 'เวกา' }).waitFor();
  await page.getByRole('button', { name: 'ซูมเข้า', exact: true }).click();
  await page.getByRole('textbox', { name: 'ค้นหาดาวหรือกลุ่มดาว' }).fill('Sirius');
  await page.locator('.search-results button').first().click();
  assert.equal(await page.getByRole('button', { name: 'ซูมออก', exact: true }).isDisabled(), true, 'search resets zoom to show horizon stars');
  await page.locator('.star-identity h2').filter({ hasText: 'ซิริอุส' }).waitFor();
  await page.getByRole('button', { name: 'บันทึกดาวนี้', exact: true }).click();
  await page.getByRole('button', { name: /บันทึกของฉัน/ }).click();
  await page.locator('.saved-card h2').filter({ hasText: 'ซิริอุส' }).waitFor();
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: /บันทึกของฉัน/ }).click();
  assert.equal(await page.locator('.saved-card').count(), 1, 'bookmark survives reload');
  await page.getByRole('button', { name: 'ดูบนแผนที่' }).click();
  await page.locator('.date-control').click();
  await page.getByLabel('วันและเวลา', { exact: true }).fill('2026-12-15T22:00');
  await page.getByRole('button', { name: 'แสดงท้องฟ้า', exact: true }).click();
  assert.ok((await page.locator('.timeline-heading strong').innerText()).includes('22:00'));
  const before = await page.locator('.star-stats strong').first().innerText();
  await page.getByRole('slider').fill('720');
  const after = await page.locator('.star-stats strong').first().innerText();
  assert.notEqual(before, after, 'time changes actual star altitude');
  assert.ok((await page.locator('.daylight-notice').innerText()).includes('กลางวัน'), 'daylight is disclosed');
  await page.getByRole('button', { name: 'กรุงเทพฯ', exact: true }).click();
  await page.getByRole('button', { name: /ซิดนีย์/ }).click();
  assert.ok((await page.locator('.map-caption').innerText()).includes('ซิดนีย์'));
  assert.ok((await page.locator('.map-caption').innerText()).includes('33.87° S'), 'southern latitude has a correct hemisphere label');
  await page.getByRole('button', { name: 'กลุ่มดาว', exact: true }).click();
  await page.getByRole('button', { name: 'ทั้งหมด', exact: true }).click();
  assert.equal(await page.locator('.constellation-card').count(), 22);
  await page.locator('.constellation-card').first().click();
  await page.locator('[data-constellation-details]').waitFor();
  await page.getByRole('button',{name:'ดูกลุ่มดาวนี้บนแผนที่',exact:true}).click();
  await page.locator('.sky-map').waitFor();
  await page.getByRole('button', { name: 'วิธีใช้แอพ', exact: true }).click();
  await page.getByRole('dialog', { name: 'เริ่มสำรวจท้องฟ้า' }).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);

  const mobile = await context.newPage();
  await mobile.setViewportSize({ width: 390, height: 844 });
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(process.env.SKY_TEST_URL || 'http://127.0.0.1:5173/Sky/?view=map', { waitUntil: 'networkidle' });
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile layout does not overflow');
  await mobile.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  await mobile.getByRole('button', { name: 'กรุงเทพฯ', exact: true }).click();
  await mobile.getByRole('button', { name: 'ใช้ตำแหน่งปัจจุบัน', exact: true }).click();
  await mobile.getByRole('alert').waitFor({ timeout: 15000 });
  assert.ok((await mobile.getByRole('alert').innerText()).length > 10, 'geolocation denial has useful fallback');
  await mobile.getByRole('button', { name: /เชียงใหม่/ }).click();
  assert.ok((await mobile.locator('.map-caption').innerText()).includes('เชียงใหม่'));
  await mobile.getByRole('button', { name: 'โหมดถนอมสายตา', exact: true }).click();
  assert.equal(await mobile.locator('.app.night-mode').count(), 1);
  await mobile.locator('.bookmark-button').click();
  const toastVisible = await mobile.locator('.toast').evaluate(el => { const box = el.getBoundingClientRect(); return box.top >= 0 && box.bottom <= innerHeight; });
  assert.equal(toastVisible, true, 'night-mode toast stays in the viewport');
  await mobile.setViewportSize({ width: 320, height: 700 });
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'small mobile layout does not overflow');
  assert.deepEqual(errors, [], 'no browser runtime errors');
  console.log('PASS: catalog, search, selection, bookmarks + reload, time, city, constellation library, zoom, layers, dialogs, mobile layout, geolocation fallback, night mode. No browser errors.');
} finally {
  await browser.close();
}
